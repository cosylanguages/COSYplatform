/**
 * Checks whether a given course object is accessible based on profile language_access and course_level.
 * @param {Object} course - Course manifest item or roadmap object
 * @param {Object} profile - User profile from profiles table
 * @returns {boolean}
 */
window.CosyAuth.isCourseAccessible = function(course, profile) {
  if (!profile) return false;

  // Founder role has unrestricted access
  if (profile.role === 'founder') return true;

  const langAccess = Array.isArray(profile.language_access) ? profile.language_access : [];
  const courseLevel = profile.course_level || '*';

  // 1. Language Check
  const courseLang = (course.lang || course.language || '').toLowerCase();
  const langAllowed = langAccess.includes('*') || langAccess.some(l => l.toLowerCase() === courseLang);

  if (!langAllowed) return false;

  // 2. Level Check
  const reqLevel = (course.level || '').toLowerCase();
  let levelAllowed = false;

  if (courseLevel === '*' || !courseLevel) {
    levelAllowed = true;
  } else if (Array.isArray(courseLevel)) {
    levelAllowed = courseLevel.includes('*') || courseLevel.some(lvl => lvl.toLowerCase() === reqLevel);
  } else if (typeof courseLevel === 'string') {
    levelAllowed = courseLevel === '*' || courseLevel.toLowerCase() === reqLevel;
  }

  return levelAllowed;
};

/**
 * Signs out current user session.
 */
window.CosyAuth.logout = async function() {
  if (supabaseClient) {
    await supabaseClient.auth.signOut();
  }
  window.location.href = "login.html";
};
