// Placeholder constants matching index.html pattern
const SUPABASE_URL = window.SUPABASE_URL || "https://your-supabase-project.supabase.co";
const SUPABASE_ANON_KEY = window.SUPABASE_ANON_KEY || "your-anon-key";

window.CosyAuth = window.CosyAuth || {};

let supabaseClient = null;
if (window.supabase && SUPABASE_URL.startsWith("http")) {
  supabaseClient = window.supabase.createClient(SUPABASE_URL, SUPABASE_ANON_KEY);
}
window.CosyAuth.client = supabaseClient;

/**
 * Loads the current session and associated user profile from Supabase.
 * Redirects to login.html if unauthenticated.
 * @returns {Promise<{session: Object, profile: Object}>}
 */
window.CosyAuth.getAuthAndProfile = async function() {
  if (!supabaseClient) {
    console.warn("Supabase client not initialized. Redirecting to login.");
    window.CosyAuth.redirectToLogin();
    return null;
  }

  const { data: { session }, error: sessionError } = await supabaseClient.auth.getSession();
  if (sessionError || !session || !session.user) {
    window.CosyAuth.redirectToLogin();
    return null;
  }

  let profile = { role: 'student', language_access: [], course_level: '*' };
  try {
    const { data, error } = await supabaseClient
      .from('profiles')
      .select('id, role, language_access, course_level')
      .eq('id', session.user.id)
      .maybeSingle();

    if (!error && data) {
      profile = data;
    }
  } catch (err) {
    console.error("Error fetching user profile:", err);
  }

  return { session, user: session.user, profile };
};

/**
 * Redirects to login page with optional return URL.
 */
window.CosyAuth.redirectToLogin = function() {
  const currentUrl = window.location.href;
  const loginUrl = `login.html?redirect=${encodeURIComponent(currentUrl)}`;
  window.location.href = loginUrl;
};

/**
 * Enforces role-based access control for entry portal pages.
 * Redirects to login if unauthenticated or renders access-denied state if role is unauthorized.
 * @param {Array<string>} allowedRoles - Allowed roles (e.g. ['founder'], ['teacher', 'founder'])
 * @returns {Promise<{session: Object, user: Object, profile: Object}>}
 */
window.CosyAuth.requireRole = async function(allowedRoles = []) {
  const authData = await window.CosyAuth.getAuthAndProfile();
  if (!authData) return null;

  const userRole = (authData.profile && authData.profile.role) ? authData.profile.role.toLowerCase() : 'student';
  const normalizedAllowed = allowedRoles.map(r => r.toLowerCase());

  if (!normalizedAllowed.includes(userRole)) {
    window.CosyAuth.renderAccessDenied(
      "Access Restricted",
      `Your current account role ('${userRole}') does not have permission to view this page.`
    );
    return null;
  }

  return authData;
};

