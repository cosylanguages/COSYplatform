    code = 1
    for n, (title, lessons) in enumerate(UNITS, 1):
        out = []
        for i, (ltitle, grammar, vocab, cando) in enumerate(lessons, 1):
            out.append(dict(
                lesson=i, type='gv', title=ltitle, duration_minutes=60,
                grammar=grammar, vocabulary=vocab,
                practice_types=['speaking', 'listening', 'reading', 'writing'],
                speaking_percent=50,
                teacher_notes=f'code: "IT-B1-{code:03d}"\ncando: "{cando}"',
                recycled='Lessico del livello A2 e del modulo precedente',
                **({'grammarIds': MAP[ltitle]} if ltitle in MAP else {})))
            code += 1
        units.append(dict(unit=n, title=f'Unità {n}: {title}', lessons=out))
    data = dict(language='it', course_type='general', level='B1', units=units)
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, 'w', encoding='utf-8') as fh:
        json.dump(data, fh, ensure_ascii=False, indent=2)
        fh.write('\n')
    print(OUT, len(units), 'units', sum(len(u['lessons']) for u in units), 'lessons')


