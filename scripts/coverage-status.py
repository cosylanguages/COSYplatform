#!/usr/bin/env python3
"""Roll every course up against the slot grid: one line per course, all levels.

`slot-alignment.py` reports one level at a time. This aggregates them so the platform's state is
readable in one place: how many lessons, how many units carry a theme, how many are grammar-only,
which slots are covered and which are not.

A1 and A2 are measured against the same grid but the comparison is informational: those levels
have their own progression and are not expected to cover thirteen B1 themes.

Usage:
  python3 scripts/coverage-status.py
  python3 scripts/coverage-status.py --write     # docs/COVERAGE_STATUS.md
"""
from __future__ import annotations

import argparse
import importlib.util
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LEVELS = ("A1", "A2", "B1", "B2", "C1", "C2")


def load_alignment():
    path = os.path.join(ROOT, "scripts", "slot-alignment.py")
    spec = importlib.util.spec_from_file_location("slot_alignment", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", nargs="?", const=os.path.join(ROOT, "docs", "COVERAGE_STATUS.md"))
    args = parser.parse_args()

    alignment = load_alignment()
    slots = json.load(open(os.path.join(ROOT, "cefr", "data", "unit-slots.json"), encoding="utf-8"))

    def grid_for(level: str) -> list[dict]:
        path = os.path.join(ROOT, "cefr", "data", f"unit-slots-{level.lower()}.json")
        if os.path.exists(path):
            return json.load(open(path, encoding="utf-8"))
        return slots
    themes = alignment.load_themes()
    grid = [s["theme"] for s in slots]

    rows = []
    for level in LEVELS:
        for name, path, data in alignment.courses(os.path.join(ROOT, "curriculums"), level):
            units = data.get("units") or []
            result = alignment.analyse(units, grid_for(level), themes)
            rows.append({
                "course": name,
                "track": name.split("-")[0],
                "language": name.split("-")[1],
                "level": level,
                "lessons": sum(len(u.get("lessons") or []) for u in units),
                "units": len(units),
                "themed": len(result["primary"]),
                "grammar_only": len(result["unthemed"]),
                "covered": len(result["covered"]),
                "missing": result["missing"],
                "duplicates": result["duplicates"],
            })

    order = {lvl: i for i, lvl in enumerate(LEVELS)}
    rows.sort(key=lambda r: (order[r["level"]], -r["covered"], r["course"]))

    lines = [
        "# Coverage status, every course against the slot grid",
        "",
        "Generated by `scripts/coverage-status.py`; regenerate, do not edit. The grid is",
        "`cefr/data/unit-slots.json` (13 themes). `grammar-only` counts units with no `theme`: they",
        "are grammar sequences whose placement in the course is real but whose topic is not declared.",
        "A1 and A2 are measured against their own grids (`unit-slots-a1.json`, `unit-slots-a2.json`),",
        "which include the topics the B1 grid leaves out (family, home, routine, food, clothes, weather,",
        "places). B1, C1 and C2 share `unit-slots.json`: C-level reuses the B1 themes with a new",
        "macro-function. An empty slot means no unit carries that theme, not that the course is bad.",
        "",
        "| course | level | lessons | units | themed | grammar-only | slots | missing |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for row in rows:
        missing = ", ".join(row["missing"]) or "-"
        lines.append(f"| {row['course']} | {row['level']} | {row['lessons']} | {row['units']} | "
                     f"{row['themed']} | {row['grammar_only']} | {row['covered']}/13 | {missing} |")

    total_courses = len(rows)
    subject = [r for r in rows if r["track"] == "general"]
    focus_languages = {"en", "fr", "ru", "it", "el"}
    focus = [r for r in subject if r["language"] in focus_languages]
    other = [r for r in subject if r["language"] not in focus_languages]
    skills = [r for r in rows if r["track"] != "general"]
    complete = [r for r in subject if r["covered"] == len(grid)]
    grammar_heavy = [r for r in focus if r["units"] and r["grammar_only"] * 2 > r["units"]]
    by_level: dict[str, list[int]] = {}
    for row in focus:
        by_level.setdefault(row["level"], []).append(row["covered"])
    lines += [
        "",
        "## What the table says",
        "",
        f"- {total_courses} courses measured: {len(subject)} subject courses (`general-*`) and "
        f"{len(skills)} single-strand courses (pronunciation, spoken, discussion, travelling, "
        "professional, exam, relocation). The latter are not expected to carry the 13-theme grid, "
        "so they are measured but excluded from the summary.",
        f"- {len(complete)} subject course(s) cover all {len(grid)} slots: "
        + (", ".join(r["course"] for r in complete) if complete else "none") + ".",
        f"- {len(other)} further subject courses ({', '.join(sorted({r['language'] for r in other}))}) "
        "are outside the current publishing plan and are not summarised.",
        "- listing courses (en, fr, ru, it, el) - median slots covered per level: "
        + ", ".join(f"{lvl} {sorted(vals)[len(vals) // 2]}/13"
                    for lvl, vals in sorted(by_level.items(), key=lambda kv: order[kv[0]])) + ".",
        f"- {len(grammar_heavy)} of those course(s) are majority grammar-only: "
        + (", ".join(r["course"] for r in grammar_heavy) if grammar_heavy else "none") + ".",
        "- A grammar-only unit is not a defect in itself; leaving it unthemed is the honest state.",
        "  It becomes a defect only when a topic label is put on it that the lessons do not serve.",
        "",
    ]

    text = "\n".join(lines)
    if args.write:
        with open(args.write, "w", encoding="utf-8") as handle:
            handle.write(text)
        print(f"wrote {os.path.relpath(args.write, ROOT)} ({total_courses} courses)")
        for row in rows:
            print(f"  {row['course']:26} {row['covered']:2}/13  themed {row['themed']:2}  "
                  f"grammar-only {row['grammar_only']:2}")
    else:
        print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
