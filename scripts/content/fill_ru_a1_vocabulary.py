def main():
    for code, words in VOCABULARY.items():
        if not all(CYRILLIC.search(w) for w in words):
            raise SystemExit(f"{code}: a word is not Russian: {words}")
        if len(set(words)) != len(words):
            raise SystemExit(f"{code}: duplicate word")

    data = json.loads(CURRICULUM.read_text(encoding="utf-8"))
    replaced, kept = 0, 0
    for unit in data["units"]:
        for lesson in unit["lessons"]:
            code = lesson["code"]
            current = lesson.get("vocabulary") or []
            if code not in VOCABULARY:
                if current and not any(CYRILLIC.search(w) for w in current):
                    raise SystemExit(f"{code}: English list, no replacement given")
                kept += 1
                continue
            if any(CYRILLIC.search(w) for w in current):
                kept += 1
                continue
            lesson["vocabulary"] = VOCABULARY.pop(code)
            replaced += 1
    if VOCABULARY:
        raise SystemExit(f"no lesson matched: {sorted(VOCABULARY)}")

    CURRICULUM.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    total = sum(len(l.get("vocabulary") or []) for u in data["units"] for l in u["lessons"])
    print(f"replaced {replaced} lists, left {kept} as they were, {total} words in the curriculum")


if __name__ == "__main__":
    main()
