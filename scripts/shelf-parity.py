#!/usr/bin/env python3
"""Compare what a lesson on the legacy XML shelf contains with what a current JSON deck contains.

The XML shelf converts cleanly (scripts/xml-lesson-to-json.py), but conversion preserves what is
there. This report answers the next question: is what is there enough? It counts, per shelf, the
proportion of lessons that carry each of the parts the platform's own decks are built from.

A can-do is read from the JSON field; a grammar focus, a reading or listening stage and a
pronunciation stage are read from the slide structure, because that is how decks express them.

Usage:
  python3 scripts/shelf-parity.py
  python3 scripts/shelf-parity.py --write      # docs/SHELF_PARITY.md
"""
from __future__ import annotations

import argparse
import collections
import glob
import importlib.util
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
converter_spec = importlib.util.spec_from_file_location(
    "xml_converter", os.path.join(ROOT, "scripts", "xml-lesson-to-json.py"))
converter = importlib.util.module_from_spec(converter_spec)
converter_spec.loader.exec_module(converter)

PARTS = (
    ("can-do", "a can-do string"),
    ("objectives", "an objectives list"),
    ("grammar focus", "a grammar-focus element"),
    ("reading / listening", "a reading or listening stage, or a reading element"),
    ("pronunciation", "a pronunciation stage"),
    ("practice task", "a test element or a controlled-practice stage"),
)


def profile(deck: dict) -> dict:
    elements = [el for slide in deck.get("slides") or [] if isinstance(slide, dict)
                for el in (slide.get("elements") or []) if isinstance(el, dict)]
    types = {el.get("type") for el in elements}
    stages = {(slide.get("stage") or "") for slide in deck.get("slides") or []
              if isinstance(slide, dict)}
    return {
        "can-do": bool((deck.get("canDo") or "").strip()),
        "objectives": bool(deck.get("objectives")),
        "grammar focus": "grammar-focus" in types,
        "reading / listening": bool(stages & {"reading-listening", "reading", "listening"})
        or bool(types & {"reading-insight", "reading"}),
        "pronunciation": "pronunciation" in stages,
        "practice task": bool(types & {"test", "error-correction"})
        or "controlled-practice" in stages,
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", nargs="?", const=os.path.join(ROOT, "docs", "SHELF_PARITY.md"))
    args = parser.parse_args()

    shelves: dict[str, list[dict]] = collections.defaultdict(list)
    for path in sorted(glob.glob(os.path.join(ROOT, "lessons", "**", "*.json"), recursive=True)):
        try:
            deck = json.load(open(path, encoding="utf-8"))
        except (OSError, ValueError):
            continue
        if isinstance(deck, dict) and deck.get("slides"):
            shelves["JSON"].append(deck)
    for path in sorted(glob.glob(os.path.join(ROOT, "lessons", "**", "*.xml"), recursive=True)):
        try:
            shelves["XML (converted)"].append(converter.convert(path))
        except Exception:
            continue

    lines = [
        "# Shelf parity: what the legacy XML lessons contain",
        "",
        "Generated by `scripts/shelf-parity.py`; regenerate, do not edit.",
        "",
        "The XML shelf converts to JSON without losing a word (see `XML_MIGRATION_DRY_RUN.md`).",
        "This report asks whether what it holds is enough: for each shelf, the share of lessons that",
        "carry each part a CosyLanguages deck is built from.",
        "",
    ]
    for name, decks in shelves.items():
        slides = [len(d.get("slides") or []) for d in decks]
        avg = sum(slides) / len(slides) if slides else 0
        lines += [f"## {name}: {len(decks)} lessons, {avg:.1f} slides on average", "",
                  "| part | lessons that have it | share |", "|---|---|---|"]
        for part, description in PARTS:
            have = sum(1 for d in decks if profile(d)[part])
            share = have / len(decks) if decks else 0
            lines.append(f"| {description} | {have} | {share:.0%} |")
        lines.append("")
    text = "\n".join(lines) + "\n"
    if args.write:
        with open(args.write, "w", encoding="utf-8") as handle:
            handle.write(text)
        print(f"wrote {os.path.relpath(args.write, ROOT)}")
    else:
        print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
