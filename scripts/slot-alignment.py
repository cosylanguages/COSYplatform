#!/usr/bin/env python3
"""Compare a level's themed units with the canonical slot grid (cefr/data/unit-slots.json).

Reads only; prints a markdown matrix and the findings that follow from it. With --write it saves
docs/<LEVEL>_SLOT_ALIGNMENT.md.

Usage:
  python3 scripts/slot-alignment.py --level B1
  python3 scripts/slot-alignment.py --level B1 --write
"""
from __future__ import annotations

import argparse
import glob
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SLOTS = os.path.join(ROOT, "cefr", "data", "unit-slots.json")
THEMES = os.path.join(ROOT, "cefr", "data", "themes.json")


def load_themes() -> dict:
    data = json.load(open(THEMES, encoding="utf-8"))
    return {t["id"]: t.get("name", t["id"]) for t in data}


def courses(curricula: str, level: str) -> list[tuple[str, str, dict]]:
    out = []
    for path in sorted(glob.glob(os.path.join(curricula, "*", "*", f"{level}.json"))):
        parts = os.path.normpath(path).split(os.sep)
        lang, track = parts[-3], parts[-2]
        out.append((f"{track}-{lang}-{level.lower()}", path, json.load(open(path, encoding="utf-8"))))
    return out


def analyse(units: list[dict], slots: list[dict], themes: dict) -> dict:
    grid = [s["theme"] for s in slots]
    primary: dict[str, list[int]] = {}
    unthemed = []
    for unit in units:
        theme = unit.get("theme")
        if not theme:
            unthemed.append(unit)
            continue
        primary.setdefault(theme, []).append(int(unit.get("unit", 0)))
    covered = [t for t in grid if t in primary]
    missing = [t for t in grid if t not in primary]
    duplicates = {t: n for t, n in primary.items() if len(n) > 1}
    off_grid = {t: n for t, n in primary.items() if t not in grid}
    return {
        "primary": primary,
        "covered": covered,
        "missing": missing,
        "duplicates": duplicates,
        "off_grid": off_grid,
        "unthemed": unthemed,
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--level", default="B1")
    parser.add_argument("--grid", help="level whose theme grid applies (default: --level). B2-C2 "
                                       "reuse the B1 themes with a new macro-function.")
    parser.add_argument("--curricula", default=os.path.join(ROOT, "curriculums"))
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()

    level = args.level.upper()
    grid = (args.grid or level).upper()
    grid_path = os.path.join(ROOT, "cefr", "data", f"unit-slots-{grid.lower()}.json")
    slots = json.load(open(grid_path if os.path.exists(grid_path) else SLOTS, encoding="utf-8"))
    themes = load_themes()
    rows = [(name, path, data, analyse(data.get("units") or [], slots, themes))
            for name, path, data in courses(args.curricula, level)]
    themed = [r for r in rows if any(r[3]["primary"].values())]

    lines = [f"# {level} slot alignment", "",
             f"Generated by `scripts/slot-alignment.py --level {level} --grid {grid}` from the goal "
             "grid and the `theme` fields of the curricula. Regenerate after any unit is re-themed; "
             "do not edit.",
             "",
             "## Matrix", "",
             "A cell shows the unit number whose **primary** theme matches the slot; `—` means the "
             "course has no unit for that slot.", ""]

    header = "| slot | theme | theme name | " + " | ".join(name for name, *_ in themed) + " |"
    lines += [header, "|" + "---|" * (3 + len(themed))]
    for slot in slots:
        cells = []
        for _, _, _, result in themed:
            units = result["primary"].get(slot["theme"], [])
            cells.append(", ".join(str(u) for u in units) if units else "—")
        lines.append(f"| {slot['slot']} | {slot['theme']} | {themes.get(slot['theme'], '')} | "
                     + " | ".join(cells) + " |")

    lines += ["", "## Findings", ""]
    for name, path, data, result in themed:
        covered, total = len(result["covered"]), len(slots)
        lines.append(f"### {name} — {covered}/{total} slots, "
                     f"{len(result['primary'])} themed units, {len(result['unthemed'])} unthemed")
        if result["missing"]:
            lines.append(f"- missing slots: " + ", ".join(
                f"{t} ({themes.get(t, '')})" for t in result["missing"]))
        if result["duplicates"]:
            lines.append("- duplicate primary themes: " + "; ".join(
                f"{t} in units {n}" for t, n in result["duplicates"].items()))
        if result["off_grid"]:
            lines.append("- off-grid themes: " + "; ".join(
                f"{t} in units {n}" for t, n in result["off_grid"].items()))
        for unit in result["unthemed"]:
            lines.append(f"- unthemed unit {unit.get('unit')}: {unit.get('title')} "
                         f"({len(unit.get('lessons') or [])} lessons)")
        lines.append("")

    not_themed = [name for name, _, _, result in rows if not any(result["primary"].values())]
    if not_themed:
        lines += ["## Not themed at this level", ""] + [f"- {name}" for name in not_themed] + [""]

    text = "\n".join(lines).rstrip() + "\n"
    if args.write:
        out = os.path.join(ROOT, "docs", f"{level}_SLOT_ALIGNMENT.md")
        with open(out, "w", encoding="utf-8") as handle:
            handle.write(text)
        print(f"wrote {os.path.relpath(out, ROOT)}")
    else:
        print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
