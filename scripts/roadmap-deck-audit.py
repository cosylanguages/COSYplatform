#!/usr/bin/env python3
"""Audit the link between roadmaps and the decks they point at.

Four checks, all objective:
  1. an entry that names a lessonFile which does not exist
  2. a deck whose own `level` disagrees with the level of the course that uses it
  3. a deck with no `canDo` (a deck that cannot state its purpose)
  4. a deck used by more than one course (informational: the platform allows reuse, but a B1 deck
     inside an A2 course is a level problem, not just reuse)

Usage:
  python3 scripts/roadmap-deck-audit.py
  python3 scripts/roadmap-deck-audit.py --write     # docs/ROADMAP_DECK_AUDIT.md
"""
from __future__ import annotations

import argparse
import collections
import glob
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def load_deck(path: str, cache: dict) -> dict | None:
    if path in cache:
        return cache[path]
    deck = None
    try:
        with open(path, encoding="utf-8") as handle:
            data = json.load(handle)
        if isinstance(data, dict):
            deck = data
    except (OSError, ValueError):
        deck = None
    cache[path] = deck
    return deck


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", nargs="?", const=os.path.join(ROOT, "docs", "ROADMAP_DECK_AUDIT.md"))
    args = parser.parse_args()

    cache: dict = {}
    missing: list[tuple[str, str, str]] = []
    level_mismatch: list[tuple[str, str, str, str]] = []
    no_cando: list[tuple[str, str, str]] = []
    users: dict[str, set] = collections.defaultdict(set)
    xml_only: collections.Counter = collections.Counter()
    entries = 0

    for rm_path in sorted(glob.glob(os.path.join(ROOT, "roadmaps", "*.json"))):
        course = os.path.basename(rm_path)[:-5]
        with open(rm_path, encoding="utf-8") as handle:
            roadmap = json.load(handle)
        tokens = {t.upper() for t in re.findall(r"a[0-9]|b[12]|c[12]", course)}
        for entry in roadmap.get("sequence") or []:
            lesson_file = (entry.get("lessonFile") or "").strip()
            if not lesson_file:
                continue
            entries += 1
            path = os.path.join(ROOT, lesson_file)
            status = (entry.get("status") or "").lower()
            if not os.path.exists(path):
                missing.append((course, lesson_file, status))
                continue
            if path.lower().endswith(".xml"):
                xml_only[course] += 1
                continue
            deck = load_deck(path, cache)
            if deck is None:
                missing.append((course, lesson_file + " (unparseable JSON)", status))
                continue
            users[lesson_file].add(course)
            deck_level = (deck.get("level") or "").upper()
            deck_tokens = {t for t in re.findall(r"A[0-9]|B[12]|C[12]", deck_level)}
            if tokens and deck_tokens and not (tokens & deck_tokens):
                level_mismatch.append((course, "/".join(sorted(tokens)), lesson_file, deck_level))
            if not (deck.get("canDo") or "").strip():
                no_cando.append((course, lesson_file, deck_level or "?"))

    reused = {path: cs for path, cs in users.items() if len(cs) > 1}
    lines = [
        "# Roadmap to deck audit",
        "",
        "Generated by `scripts/roadmap-deck-audit.py`; regenerate, do not edit.",
        "",
        f"- roadmap entries pointing at a deck: {entries}",
        f"- entries whose file does not exist: {len(missing)}",
        f"- decks whose level disagrees with the course using them: {len(level_mismatch)}",
        f"- entries pointing at an XML lesson (legacy format, not audited here): "
        f"{sum(xml_only.values())}",
        f"- decks with no can-do: {len(no_cando)}",
        f"- decks used by more than one course: {len(reused)}",
        "",
        "## Level mismatches",
        "",
        "A B1 deck inside an A2 course is a level problem even when the reuse itself is intended.",
        "",
    ]
    if level_mismatch:
        lines += ["| course | course level | deck | deck level |", "|---|---|---|---|"]
        for course, c_level, path, d_level in level_mismatch[:60]:
            lines.append(f"| {course} | {c_level} | {os.path.basename(path)} | {d_level} |")
        if len(level_mismatch) > 60:
            lines.append(f"| ... | | {len(level_mismatch) - 60} more | |")
    else:
        lines.append("None.")

    lines += ["", "## Entries with no file behind them, by course", "",
              "An entry whose `lessonFile` does not exist is a slot the roadmap promises and the app",
              "cannot open. The `planned` column counts entries that say so themselves.", "",
              "| course | entries with no file | of which marked planned |", "|---|---|---|"]
    by_course_missing = collections.Counter(course for course, _, _ in missing)
    planned_by_course = collections.Counter(course for course, _, st in missing
                                            if st in ("planned", "upcoming", "todo"))
    if not by_course_missing:
        lines.append("| none | 0 | 0 |")
    for course, count in by_course_missing.most_common():
        lines.append(f"| {course} | {count} | {planned_by_course.get(course, 0)} |")

    lines += ["", "## Entries pointing at XML lessons, by course", "",
              "These are legacy `.xml` lesson files. They exist and the app can load them through the",
              "old content table, but they carry no JSON metadata, so nothing in this audit - can-do,",
              "level, unit theme - can be checked for them.", "",
              "| course | XML entries |", "|---|---|"]
    for course, count in xml_only.most_common():
        lines.append(f"| {course} | {count} |")

    lines += ["", "## Decks without a can-do", ""]
    if no_cando:
        by_course = collections.Counter(course for course, _, _ in no_cando)
        lines += ["| course | decks without can-do |", "|---|---|"]
        for course, count in by_course.most_common():
            lines.append(f"| {course} | {count} |")
    else:
        lines.append("None.")

    extensions = collections.Counter(os.path.splitext(p)[1].lower() or "(none)" for p in users)
    lines += ["", "## File formats the roadmaps point at", "",
              "| extension | distinct files |", "|---|---|"]
    for ext, count in extensions.most_common():
        lines.append(f"| {ext} | {count} |")

    lines += ["", "## Decks used by more than one course", ""]
    by_pair = collections.Counter(tuple(sorted(cs)) for cs in reused.values())
    if by_pair:
        lines += ["| courses sharing decks | decks |", "|---|---|"]
        for courses, count in by_pair.most_common(20):
            lines.append(f"| {' + '.join(courses)} | {count} |")
    else:
        lines.append("None.")

    text = "\n".join(lines) + "\n"
    if args.write:
        with open(args.write, "w", encoding="utf-8") as handle:
            handle.write(text)
        print(f"wrote {os.path.relpath(args.write, ROOT)}")
    else:
        print(text)
    print(f"entries {entries} | missing {len(missing)} | level mismatch {len(level_mismatch)} | "
          f"no can-do {len(no_cando)} | shared decks {len(reused)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
